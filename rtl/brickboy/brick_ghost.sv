// 23040 x 24. Read at s0, written back at s2 - the same pixel is never
// revisited inside that window, so no forwarding is needed.
// Selectable source gamma tables. The inverse stores adjacent 512-sample
// values as one 16-bit word so each colour channel needs only one ROM read.
(* ramstyle = "M10K" *) reg [15:0] GHOST_FWD[0:1023];
(* ramstyle = "M10K" *) reg [15:0] GHOST_INV[0:2047];
initial begin
	$readmemh("rtl/brickboy/brick_ghost_fwd.hex", GHOST_FWD);
	$readmemh("rtl/brickboy/brick_ghost_inv.hex", GHOST_INV);
end

reg [23:0] gstate[0:23039];

wire [14:0] addr = {in_row, 7'b0} + {2'b0, in_row, 5'b0} + in_x;

reg [14:0] a1, a2;
reg [23:0] tgt1, tgt2;
reg [23:0] st1;
reg [7:0]  x1, x2;
reg        v1, v2;

// s0: issue the read
always @(posedge clk) begin
	v1   <= in_v;
	x1   <= in_x;
	a1   <= addr;
	tgt1 <= in_rgb;
	st1  <= gstate[addr];
end

// The relaxation is split across stages: two chained LUTs plus a multiply do
// not close at 33.5 MHz in one hop. Reading the forward LUT, the IIR multiply,
// and the interpolated inverse each get their own.

function automatic [7:0] absd(input [7:0] a, input [7:0] b);
	absd = (a > b) ? (a - b) : (b - a);
endfunction

wire [7:0] tr = tgt1[23:16], tg = tgt1[15:8], tb = tgt1[7:0];
wire [7:0] sr = st1[23:16],  sg = st1[15:8],  sb = st1[7:0];

wire [7:0]  dr = absd(tr, sr);
wire [7:0]  dg = absd(tg, sg);
wire [7:0]  db = absd(tb, sb);
wire [17:0] sumsq = dr*dr + dg*dg + db*db;
wire [7:0]  snap_raw  = (sumsq[17:10] != 8'd0) ? 8'd0 : LUT_SNAP[sumsq[9:2]];
wire [7:0]  gate_scale = (gate == 2'd1) ? 8'd160 :
                         (gate == 2'd2) ? 8'd224 : 8'd255;
wire [15:0] snap_scaled = snap_raw * gate_scale;
wire [7:0]  snap = (snap_raw == 8'd255) ? 8'd255 : snap_scaled[15:8];

// s0b: the gate. Coming straight off the state RAM, the squared length plus
// the LUT plus the alpha mix is one hop too many, so the gate gets its own.
reg [7:0]  snap_r;
reg [23:0] tgt1b, st1b;
reg [14:0] a1a; reg [7:0] x1a; reg v1a;

reg dark_r, dark_g, dark_b;

always @(posedge clk) begin
	v1a <= v1; x1a <= x1; a1a <= a1;
	tgt1b <= tgt1; st1b <= st1;
	snap_r <= snap;
	// direction resolved here so s1 only has to pick a constant
	dark_r <= (st1[23:16] >= tgt1[23:16]);
	dark_g <= (st1[15:8]  >= tgt1[15:8]);
	dark_b <= (st1[7:0]   >= tgt1[7:0]);
end

// s1: forward LUTs + alpha
wire [7:0] tr2 = tgt1b[23:16], tg2 = tgt1b[15:8], tb2 = tgt1b[7:0];
wire [7:0] sr2 = st1b[23:16],  sg2 = st1b[15:8],  sb2 = st1b[7:0];

reg [15:0] ftr, ftg, ftb, fsr, fsg, fsb;
reg [8:0]  ar, ag, ab;
reg [14:0] a1b; reg [7:0] x1b; reg v1b;

function automatic [8:0] alpha_of(input dark, input [7:0] sn);
	reg [7:0]  base;
	reg [16:0] w;
	begin
		base     = dark ? A_FALL : A_RISE;       // driven is fast, relaxing slow
		w        = (9'd256 - base) * sn;
		alpha_of = base + w[16:8];
	end
endfunction

always @(posedge clk) begin
	v1b <= v1a; x1b <= x1a; a1b <= a1a;
	ftr <= GHOST_FWD[{gamma,tr2}]; fsr <= GHOST_FWD[{gamma,sr2}]; ar <= alpha_of(dark_r, snap_r);
	ftg <= GHOST_FWD[{gamma,tg2}]; fsg <= GHOST_FWD[{gamma,sg2}]; ag <= alpha_of(dark_g, snap_r);
	ftb <= GHOST_FWD[{gamma,tb2}]; fsb <= GHOST_FWD[{gamma,sb2}]; ab <= alpha_of(dark_b, snap_r);
end

// s1b: the IIR step in transmittance space
reg [15:0] nr, ng, nb;
reg [14:0] a1c; reg [7:0] x1c; reg v1c;

function automatic [15:0] step22(input [15:0] f_t, input [15:0] f_s, input [8:0] a);
	reg signed [25:0] d;
	reg signed [17:0] v;
	begin
		d = ($signed({1'b0, f_t}) - $signed({1'b0, f_s})) * $signed({1'b0, a});
		v = $signed({2'b0, f_s}) + (d >>> 8);
		step22 = (v < 0) ? 16'd0 : (v > 18'sd65535) ? 16'd65535 : v[15:0];
	end
endfunction

always @(posedge clk) begin
	v1c <= v1b; x1c <= x1b; a1c <= a1b;
	nr <= step22(ftr, fsr, ar);
	ng <= step22(ftg, fsg, ag);
	nb <= step22(ftb, fsb, ab);
end

// s1c: inverse LUT fetch. The interpolation is a separate hop - a 2048-entry
// LUT read followed by a multiply and an add is one gate level too many here.
reg [7:0]  lor, hir, log_, hig, lob, hib;
reg [6:0]  frr, frg, frb;
reg [14:0] a1d; reg [7:0] x1d; reg v1d;

wire [8:0] ir = nr[15:7], ig = ng[15:7], ib = nb[15:7];
wire [15:0] invr = GHOST_INV[{gamma,ir}];
wire [15:0] invg = GHOST_INV[{gamma,ig}];
wire [15:0] invb = GHOST_INV[{gamma,ib}];

always @(posedge clk) begin
	v1d <= v1c; x1d <= x1c; a1d <= a1c;
	lor <= invr[7:0]; hir <= invr[15:8]; frr <= nr[6:0];
	log_ <= invg[7:0]; hig <= invg[15:8]; frg <= ng[6:0];
	lob <= invb[7:0]; hib <= invb[15:8]; frb <= nb[6:0];
end

// s1d: interpolate
function automatic [7:0] lerp7(input [7:0] lo, input [7:0] hi, input [6:0] f);
	reg [14:0] d;
	begin
		d     = (hi - lo) * f;
		lerp7 = lo + d[14:7];
	end
endfunction

always @(posedge clk) begin
	v2 <= v1d; x2 <= x1d; a2 <= a1d;
	tgt2 <= { lerp7(lor, hir, frr), lerp7(log_, hig, frg), lerp7(lob, hib, frb) };
end

// s2: write the new state back and emit it
always @(posedge clk) begin
	out_v   <= v2;
	out_x   <= x2;
	out_rgb <= tgt2;
	if (v2) gstate[a2] <= tgt2;
end

