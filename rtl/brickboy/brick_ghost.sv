// BrickBoy persistence - the HW form of brickboy's FRAG_GHOST.
//
// Every pixel holds an analog cell state that relaxes toward the freshly
// coloured target:  state += (target - state) * (1 - exp(-dt/tau))
//
// The direction matters and is easy to get backwards. The GB panel is normally
// white: driving it dark twists the crystal and is FAST, letting it go light is
// elastic relaxation and is SLOW. So the trail lives on the lightening side -
// behind a sprite that has left, not in front of it.
//
//   tauRise = 8 + 102 * 0.52 = 61.04 ms  ->  alpha 61/256   (going light, slow)
//   tauFall = tauRise * 0.35 = 21.36 ms  ->  alpha 139/256  (going dark, fast)
//
// dt is one GB frame (16.742 ms) exactly - the raster is frame-locked, so there
// is no jitter to clamp, unlike the shader which takes real elapsed time.
//
// Relaxation runs in transmittance space (ghost.gamma 2.2), so mid-grey trails
// carry the right weight. Forward is a 256-entry LUT to 16 bits; the inverse is
// a 2048-entry LUT with linear interpolation on the low bits, because x^(1/2.2)
// expands the dark end and a plain 8-bit inverse would band there.
//
// The luminance gate (ghost.gate 0.05) snaps small deltas so static content
// stays crisp. The shader takes a 3-component length; here the squared length
// indexes the smoothstep LUT directly, which avoids a square root and is exact.
//
// DEVIATION from brickboy (plan 3-3(1)): the shader holds the state AFTER the
// dot grid; that needs 8.85 Mbit at 4x and does not fit. The state here is the
// native-resolution colour, and the grid is applied later, on the way out.

module brick_ghost (
	input  wire        clk,

	input  wire        in_v,
	input  wire [7:0]  in_row,
	input  wire [7:0]  in_x,
	input  wire [23:0] in_rgb,
	input  wire [1:0]  strength, // Original, off, low, high
	input  wire [1:0]  gate,     // Original, soft, hard, maximum
	input  wire [1:0]  gamma,    // Original 2.2, linear, 1.6, 3.0
	input  wire [1:0]  cold,     // source temperature samples 0, .25, .5, 1

	output reg         out_v,
	output reg  [7:0]  out_x,
	output reg  [23:0] out_rgb
);

